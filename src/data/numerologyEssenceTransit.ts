/**
 * CALCULATION ENGINE FOR TRANSIT CYCLES & ESSENCE NUMBERS
 */

function cleanNameLetters(name: string): string[] {
  return name.toUpperCase().replace(/[^A-Z]/g, "").split("");
}

function getChaldeanValue(char: string): number {
  const info = CHALDEAN_LETTER_DURATIONS[char];
  return info ? info.durationYears : 1;
}

function reduceToSingleDigitOrMaster(n: number): number {
  if (n === 11 || n === 22 || n === 33) return n;
  let curr = n;
  while (curr > 9 && curr !== 11 && curr !== 22 && curr !== 33) {
    curr = String(curr).split("").reduce((a, b) => a + Number(b), 0);
  }
  return curr;
}

function reduceToSingleDigitStrict(n: number): number {
  let curr = n;
  while (curr > 9) {
    curr = String(curr).split("").reduce((a, b) => a + Number(b), 0);
  }
  return curr;
}

export interface NameTransitSequence {
  letters: string[];
  durations: number[];
  totalCycleYears: number;
}

export function buildNameTransitSequence(namePart: string): NameTransitSequence {
  const letters = cleanNameLetters(namePart);
  const durations = letters.map(getChaldeanValue);
  const totalCycleYears = durations.reduce((a, b) => a + b, 0) || 1;
  return { letters, durations, totalCycleYears };
}

export function getActiveLetterForAge(seq: NameTransitSequence, age: number): { letter: string; value: number } {
  if (!seq.letters.length) return { letter: "A", value: 1 };
  
  const remainder = age % seq.totalCycleYears;
  let accumulated = 0;

  for (let i = 0; i < seq.letters.length; i++) {
    accumulated += seq.durations[i];
    if (remainder < accumulated) {
      return { letter: seq.letters[i], value: seq.durations[i] };
    }
  }

  return { letter: seq.letters[0], value: seq.durations[0] };
}

export function calculateLifetimeTransitTimeline(
  firstName: string,
  middleName: string,
  lastName: string,
  birthYear: number,
  birthMonth: number,
  birthDay: number,
  maxAge: number = 85
): TransitCycleTimelineYear[] {
  const fnSeq = buildNameTransitSequence(firstName);
  const mnSeq = middleName.trim() ? buildNameTransitSequence(middleName) : null;
  const snSeq = buildNameTransitSequence(lastName);

  const dayReduced = reduceToSingleDigitStrict(birthDay);
  const monthReduced = reduceToSingleDigitStrict(birthMonth);

  const timeline: TransitCycleTimelineYear[] = [];

  for (let age = 0; age <= maxAge; age++) {
    const calendarYear = birthYear + age;

    const fnActive = getActiveLetterForAge(fnSeq, age);
    const snActive = getActiveLetterForAge(snSeq, age);

    let rawSum = fnActive.value + snActive.value;
    let mnActiveLetter: string | undefined = undefined;
    let mnActiveValue: number | undefined = undefined;

    if (mnSeq && mnSeq.letters.length > 0) {
      const mnActive = getActiveLetterForAge(mnSeq, age);
      mnActiveLetter = mnActive.letter;
      mnActiveValue = mnActive.value;
      rawSum += mnActive.value;
    }

    const essenceNumber = reduceToSingleDigitOrMaster(rawSum);
    const isMasterEssence = essenceNumber === 11 || essenceNumber === 22 || essenceNumber === 33;

    // Personal Year Calculation for this calendar year
    const yearDigitsSum = String(calendarYear).split("").reduce((a, b) => a + Number(b), 0);
    const targetYearReduced = reduceToSingleDigitStrict(yearDigitsSum);
    const personalYearNumber = reduceToSingleDigitStrict(dayReduced + monthReduced + targetYearReduced);

    // Relationship Pattern between Personal Year and Essence Number
    const essSingle = reduceToSingleDigitStrict(essenceNumber);
    let relationshipPattern: "Alignment" | "Productive Tension" | "Genuine Challenge" = "Productive Tension";
    let relationshipNotes = "";

    if (essSingle === personalYearNumber) {
      relationshipPattern = "Alignment";
      relationshipNotes = `Perfect Alignment: Both Personal Year ${personalYearNumber} and Essence ${essenceNumber} share the same vibrational current, creating peak momentum.`;
    } else if (
      (personalYearNumber === 1 && essSingle === 9) ||
      (personalYearNumber === 9 && essSingle === 1) ||
      (personalYearNumber === 4 && essSingle === 5) ||
      (personalYearNumber === 5 && essSingle === 4) ||
      (personalYearNumber === 7 && essSingle === 8) ||
      (personalYearNumber === 8 && essSingle === 7)
    ) {
      relationshipPattern = "Genuine Challenge";
      relationshipNotes = `Genuine Challenge: Personal Year ${personalYearNumber} and Essence ${essenceNumber} pull in opposing directions, requiring conscious spiritual integration.`;
    } else {
      relationshipPattern = "Productive Tension";
      relationshipNotes = `Productive Tension: Personal Year ${personalYearNumber} and Essence ${essenceNumber} complement each other, offering multi-dimensional growth.`;
    }

    timeline.push({
      age,
      calendarYear,
      firstNameLetter: fnActive.letter,
      firstNameValue: fnActive.value,
      middleNameLetter: mnActiveLetter,
      middleNameValue: mnActiveValue,
      surnameLetter: snActive.letter,
      surnameValue: snActive.value,
      rawEssenceSum: rawSum,
      essenceNumber,
      isMasterEssence,
      relationshipPattern,
      relationshipNotes
    });
  }

  return timeline;
}

export function getEssenceDetail(num: number): EssenceNumberDetail {
  return ALL_ESSENCE_DATABASE[num] || ALL_ESSENCE_DATABASE[1];
}

export function getChaldeanLetterInfo(letter: string): ChaldeanLetterTransitInfo {
  const upper = letter.toUpperCase();
  return CHALDEAN_LETTER_DURATIONS[upper] || CHALDEAN_LETTER_DURATIONS["A"];
}
